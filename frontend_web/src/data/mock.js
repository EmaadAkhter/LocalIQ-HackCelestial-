export function calculateMatchScore(userAnswers, personAnswers) {
  if (!userAnswers || !personAnswers) return 0;

  const total = Object.keys(userAnswers).length;
  let matched = 0;

  Object.entries(userAnswers).forEach(([key, value]) => {
    if (personAnswers[key] === value) matched += 1;
  });

  return Math.round((matched / total) * 100);
}

