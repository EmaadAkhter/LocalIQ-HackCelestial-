export function rightNowLabel(score) {
  if (score >= 85) return 'Great right now';
  if (score >= 70) return 'Good soon';
  return 'Better later';
}

export function computeRightNow(experience, { raining, hour }) {
  let score = experience.rightNowBase;
  if (raining) score += experience.rainSafe ? 18 : -22;
  if (hour >= 17 && hour <= 19 && experience.timeOfDay === 'evening') score += 10;
  if (hour >= 6 && hour <= 10 && experience.timeOfDay === 'morning') score += 8;
  if (hour >= 20 && experience.timeOfDay === 'night') score += 12;
  if (experience.crowd === 'High' && raining) score -= 6;
  return Math.max(8, Math.min(99, Math.round(score)));
}

export function contextLine(experience, raining) {
  if (raining && experience.rainSafe) return 'Rain expected — indoor and covered options prioritized.';
  if (raining && !experience.rainSafe) return 'Open-air plan; flagged because rain is in the next 20 minutes.';
  if (experience.timeOfDay === 'evening') return `Sunset window is tight — best between ${experience.bestTime}.`;
  if (experience.crowd === 'Low') return 'Low crowd and good lighting for a solo-friendly outing.';
  return `Time-of-day fit: ${experience.bestTime}.`;
}
